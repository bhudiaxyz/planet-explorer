export interface WorldPalette {
  // terrain biome
  sand: string;
  grass: string;
  forest: string;
  rock: string;
  snow: string;
  water: string;
  snowline: number;
  forestDensity: number;
  // sky
  skyNight: string;
  skyDay: string;
  skySunset: string;
  sunLight: string;
  sunsetLight: string;
  moonLight: string;
  ambientLight: string;
  sunDisc: [number, number, number];
  moonDisc: [number, number, number];
  // atmosphere
  atmosphereScatter: string;
  atmosphereLimb: string;
  // precipitation
  rain: string;
  // rocks
  rockWarm: string;
  rockWarmAlt: string;
  rockWarmDark: string;
  rockCool: string;
  // landmarks
  landmarkStone: string;
  landmarkDark: string;
  landmarkStoneBark: string;
  islandTurf: string[]; // 4 entries: autumn, teal, violet, frost (index 0 uses grass biome)
  islandRock: string[]; // 4 variants
  islandFoliage: string[]; // 5 variants
  islandPond: string;
  islandFoam: string;
  crystals: [number, number, number][]; // HDR RGB emissive triples
  // plants
  plantStem: string;
  cactusSkin: string;
  cactusBase: string;
  // trees — one entry per species: pine oak birch palm fir snag acacia cypress willow mangrove
  treeLeavesHSL: [number, number, number][];
  treeBark: string[];
  treeBarkLow: string; // generic trunk for low-poly blob tier (oak/birch low-poly)
}

